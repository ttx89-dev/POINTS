#!/usr/bin/env python3
"""Generate the committed documentation assets from repository-verified data.

Deterministic: every pixel and every SVG shape derives from bytes present in
suite/tests/golden_corpus.py (entry "demo_graph", the Mechanical Watch
ontology). Nothing is invented — the script prints exactly what it computed.

Outputs (written under assets/ at the repository root):

  assets/sample_glyph.png   dot raster of the golden demo glyph — one dot
                            per glyph bit, cropped to the declared content
                            band (first 768 of 8,192 bytes; the tail of a
                            small graph is zero padding, shown nowhere else)
  assets/banner.svg         README banner; its dot strip is drawn from
                            glyph content bytes, not decoration

Rendering convention (declared here and in the image caption): glyph bits
are laid out row-major, MSB-first within each byte. The 8,192 bytes of a
glyph ARE a 65,536-dot matrix; the raster shows the head of that matrix.

Run:

    python3 tools/render_glyph_assets.py        # from the repository root

Regenerates byte-identical assets (no timestamps embedded).
"""

from __future__ import annotations

import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from suite.tests.golden_corpus import CORPUS

ASSETS = os.path.join(REPO, "assets")
INK = (17, 16, 20)        # background
DOT = (245, 197, 123)     # raised-dot colour
PAD = 24
SCALE = 3                 # each dot is 3x3 px
CROP_BYTES = 768          # content band shown in the raster (of 8,192)


def render_sample_png() -> str:
    """Dot raster of the golden demo glyph, cropped to the content band."""
    from PIL import Image, ImageDraw, ImageFont

    packed = CORPUS["demo_graph"]["packed"]
    n = len(packed)
    assert n == 8192, f"expected an 8,192-byte glyph, got {n}"

    cols = 256
    rows = CROP_BYTES * 8 // cols          # 24 dot rows
    band = packed[:CROP_BYTES]

    caption_h = 26
    width = cols * SCALE + PAD * 2
    height = rows * SCALE + PAD * 2 + caption_h
    img = Image.new("RGB", (width, height), INK)
    d = ImageDraw.Draw(img)

    bits_set = 0
    for i, byte in enumerate(band):
        for b in range(8):
            if (byte >> (7 - b)) & 1:
                bits_set += 1
                row, col = divmod(i * 8 + b, cols)
                x, y = PAD + col * SCALE, PAD + row * SCALE
                d.ellipse((x, y, x + SCALE * 0.92, y + SCALE * 0.92), fill=DOT)

    # hairline frame marking the raster bounds
    d.rectangle((PAD - 6, PAD - 6, PAD + cols * SCALE + 5, PAD + rows * SCALE + 5),
                outline=(60, 58, 66), width=1)

    try:
        font = ImageFont.load_default(size=13)
    except TypeError:
        font = ImageFont.load_default()
    d.text((PAD, PAD + rows * SCALE + 7),
           "golden glyph demo_graph - dots 0..6143 of 65,536 "
           "(bytes 0..767 of 8,192) - 1 dot per bit, MSB-first",
           fill=(154, 160, 172), font=font)

    out = os.path.join(ASSETS, "sample_glyph.png")
    img.save(out)
    return out, bits_set


def render_banner_svg() -> str:
    """Banner whose dot strip is drawn from glyph content bytes.

    The 64 bytes starting at byte 40 (just past the fixed header) are drawn
    as an 8x8 dot grid: a bright dot when the byte is non-zero, a faint one
    when it is null. Coordinates and content are fully deterministic.
    """
    packed = CORPUS["demo_graph"]["packed"]
    strip = packed[40:104]

    cell = 9.2
    cols, rows = 8, 8
    ox, oy = 46, 74
    dots = []
    for r in range(rows):
        for c in range(cols):
            byte = strip[r * cols + c]
            on = byte != 0
            dot = (f'<circle cx="{ox + c * cell:.1f}" cy="{oy + r * cell:.1f}" '
                   f'r="2.6" fill="#F5C97B" opacity="{1.0 if on else 0.28}"/>')
            dots.append(dot)

    tx = ox + cols * cell + 38
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="880" height="240" viewBox="0 0 880 240" role="img" aria-label="POINTS banner">
  <!-- generated by tools/render_glyph_assets.py from suite/tests/golden_corpus.py entry "demo_graph"
       (dot strip = glyph bytes 40..104, past the fixed header);
       deterministic - regenerate with: python3 tools/render_glyph_assets.py -->
  <rect width="880" height="240" rx="14" fill="#111014"/>
  <rect x="1" y="1" width="878" height="238" rx="13" fill="none" stroke="#3a3842" stroke-width="1"/>
  {"".join(dots)}
  <text x="{tx:.0f}" y="108" font-family="'DejaVu Sans Mono','JetBrains Mono',Consolas,monospace" font-size="62" font-weight="700" fill="#F5C97B" letter-spacing="2">POINTS</text>
  <text x="{tx + 2:.0f}" y="140" font-family="'DejaVu Sans Mono','JetBrains Mono',Consolas,monospace" font-size="19" fill="#E8E8EC">A knowledge graph, packed into exactly 8,192 bytes</text>
  <text x="{tx + 2:.0f}" y="166" font-family="'DejaVu Sans Mono','JetBrains Mono',Consolas,monospace" font-size="14" fill="#9AA0AC">dot-matrix encoding  &#183;  RS(255,223) + XOR parity  &#183;  multi-glyph chains</text>
  <text x="842" y="216" text-anchor="end" font-family="'DejaVu Sans Mono',Consolas,monospace" font-size="11" fill="#6E7480">glyph source: suite/tests/golden_corpus.py &#183; demo_graph</text>
</svg>
'''
    out = os.path.join(ASSETS, "banner.svg")
    with open(out, "w", encoding="utf-8") as f:
        f.write(svg)
    return out


def main() -> int:
    if not os.path.isdir(ASSETS):
        os.makedirs(ASSETS)

    packed = CORPUS["demo_graph"]["packed"]
    print('source  : suite/tests/golden_corpus.py [demo_graph]')
    print(f'glyph   : {len(packed):,} bytes ({sum(1 for b in packed if b):,} non-null)')

    png, bits = render_sample_png()
    print(f'wrote   : {os.path.relpath(png, REPO)}  '
          f'({CROP_BYTES * 8:,} dots shown, {bits:,} set; full glyph is 65,536 dots)')
    svg = render_banner_svg()
    print(f'wrote   : {os.path.relpath(svg, REPO)}  ({os.path.getsize(svg)} bytes)')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
